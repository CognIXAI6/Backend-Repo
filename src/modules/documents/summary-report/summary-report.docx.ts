const LOGO_PNG = readFileSync(join(__dirname, '..', '..', '..', 'assets', 'cognix-logo.png'));
const LOGO_ASPECT = 180 / 600;

// Same palette as the PDF (no leading '#': Word wants bare hex).
const NAVY = '101F3C';
const BLUE = '2F5FD0';
const BLUE_SOFT = '8FB0FF';
const INK = '1A1F2E';
const BODY = '2B2F3A';
const MUTED = '6B7280';
const RULE = 'DFE3EA';
const CREAM = 'F6F2E8';
const CREAM_EDGE = 'E2DAC3';
const INSIGHT_FILL = 'EAF0FD';
const INSIGHT_EDGE = 'C5D3F3';
const SPEAKER_COLOURS = ['9A6A2A', '2F7D5B', '7B3F8C', 'B13A32', '4F6490', '6F8A2C', 'A2602C', '2F6EA0', '8A4F72', '2F7F86', '6B4E9A', '9A3F5F'];
const SERIF = 'Georgia';

// A4 with 2 cm margins: 11906 - 2 × 1134 = 9638 twips of usable width.
const MARGIN = 1134;
const CONTENT_W = 9638;

const NONE = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' } as const;
const noBorders = { top: NONE, bottom: NONE, left: NONE, right: NONE } as const;
const line = (color: string, size = 4) => ({ style: BorderStyle.SINGLE, size, color }) as const;

function tint(hex: string, amount: number): string {
  const n = parseInt(hex, 16);
  const mix = (c: number) => Math.round(c + (255 - c) * amount);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => mix(c).toString(16).padStart(2, '0')).join('').toUpperCase();
}

/** Empty paragraph used as vertical space (Word also needs one between two adjacent tables). */
const spacer = (after = 200) => new Paragraph({ spacing: { before: 0, after }, children: [new TextRun({ text: '', size: 2 })] });

const run = (text: string, o: { size?: number; color?: string; bold?: boolean; italics?: boolean; spacing?: number; shade?: string } = {}) =>
  new TextRun({
    text,
    font: SERIF,
    size: o.size ?? 22,
    color: o.color ?? BODY,
    bold: o.bold,
    italics: o.italics,
    characterSpacing: o.spacing,
    ...(o.shade ? { shading: { type: ShadingType.CLEAR, color: 'auto', fill: o.shade } } : {}),
  });

/** A one-cell table: Word's way of drawing a filled, bordered box. */
function box(children: Paragraph[], o: { fill: string; borders?: Record<string, unknown>; margin?: number }): Table {
  return new Table({
    width: { size: CONTENT_W, type: WidthType.DXA },
    columnWidths: [CONTENT_W],
    layout: TableLayoutType.FIXED,
    borders: { ...noBorders, insideHorizontal: NONE, insideVertical: NONE },
    rows: [
      new TableRow({
        cantSplit: false,
        children: [
          new TableCell({
            width: { size: CONTENT_W, type: WidthType.DXA },
            shading: { type: ShadingType.CLEAR, color: 'auto', fill: o.fill },
            borders: (o.borders as never) ?? noBorders,
            margins: { top: o.margin ?? 240, bottom: o.margin ?? 240, left: 320, right: 320 },
            children,
          }),
        ],
      }),
    ],
  });
}

function sectionHeading(label: string, heading: string): Paragraph[] {
  return [
    new Paragraph({ keepNext: true, spacing: { before: 360, after: 40 }, children: [run(label, { size: 17, color: BLUE, spacing: 30 })] }),
    new Paragraph({
      keepNext: true,
      spacing: { before: 0, after: 240 },
      border: { bottom: line(RULE, 6) },
      children: [run(heading, { size: 44, color: INK })],
    }),
  ];
}

function cover(report: SummaryReport): Array<Paragraph | Table> {
  const range = formatReportRange(report.sessions.map((s) => s.date));
  const count = `${report.sessions.length} ${report.sessions.length === 1 ? 'SESSION' : 'SESSIONS'}`;
  return [
    new Paragraph({ spacing: { before: 0, after: 200 }, children: [run('MEETING INTELLIGENCE REPORT', { size: 17, color: MUTED, spacing: 30 })] }),
    box(
      [
        new Paragraph({ spacing: { after: 160 }, children: [run(range, { size: 17, color: BLUE_SOFT, spacing: 30 })] }),
        new Paragraph({ spacing: { after: 360, line: 330 }, children: [run(report.title, { size: 56, color: 'FFFFFF' })] }),
        new Paragraph({
          spacing: { after: 0 },
          children: [
            run(` ${count} `, { size: 16, color: 'FFFFFF', bold: true, spacing: 20, shade: '3B6FE0' }),
            run(`    Generated by CognIX AI  ·  ${formatGeneratedDate(report.generatedAt)}`, { size: 19, color: 'C3CDE6' }),
          ],
        }),
      ],
      { fill: NAVY, margin: 520 },
    ),
  ];
}

function contentsTable(report: SummaryReport): Array<Paragraph | Table> {
  const widths = [880, 1800, 5058, 1900];
  const head = (text: string, i: number) =>
    new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      borders: { ...noBorders, bottom: line(INK, 8) },
      margins: { top: 100, bottom: 100, left: 160, right: 160 },
      children: [new Paragraph({ alignment: i === 3 ? AlignmentType.RIGHT : AlignmentType.LEFT, children: [run(text, { size: 15, color: MUTED, spacing: 20 })] })],
    });
  const rows = [
    new TableRow({ tableHeader: true, children: ['NO.', 'DATE', 'MEETING', 'ACTION POINTS'].map(head) }),
    ...report.sessions.map(
      (s) =>
        new TableRow({
          cantSplit: true,
          children: [
            [String(s.number).padStart(2, '0'), { size: 32, color: BLUE }, AlignmentType.LEFT],
            [formatReportDate(s.date), { size: 19, color: BODY }, AlignmentType.LEFT],
            [s.title, { size: 22, color: INK }, AlignmentType.LEFT],
            [String(s.actionPoints.length), { size: 26, color: INK }, AlignmentType.RIGHT],
          ].map(
            ([text, o, align], i) =>
              new TableCell({
                width: { size: widths[i], type: WidthType.DXA },
                verticalAlign: VerticalAlign.CENTER,
                borders: { ...noBorders, bottom: line(RULE, 4) },
                margins: { top: 140, bottom: 140, left: 160, right: 160 },
                children: [new Paragraph({ alignment: align as never, children: [run(text as string, o as never)] })],
              }),
          ),
        }),
    ),
  ];
  return [
    ...sectionHeading('CONTENTS', 'Sessions at a glance'),
    new Table({ width: { size: CONTENT_W, type: WidthType.DXA }, columnWidths: widths, layout: TableLayoutType.FIXED, rows, borders: { ...noBorders, insideHorizontal: NONE, insideVertical: NONE } }),
  ];
}

function sessionBanner(number: number, isoDate: string, title: string, description: string): Array<Paragraph | Table> {
  return [
    // A page break before every session keeps each conversation in its own section.
    new Paragraph({ pageBreakBefore: true, spacing: { before: 0, after: 0 }, children: [new TextRun({ text: '', size: 2 })] }),
    box(
      [
        new Paragraph({ spacing: { after: 120 }, children: [run(`SESSION ${String(number).padStart(2, '0')}  ·  ${formatReportDate(isoDate)}`, { size: 16, color: BLUE_SOFT, bold: true, spacing: 26 })] }),
        new Paragraph({ spacing: { after: description ? 160 : 0, line: 300 }, children: [run(title, { size: 42, color: 'FFFFFF' })] }),
        ...(description ? [new Paragraph({ spacing: { after: 0, line: 290 }, children: [run(description, { size: 21, color: 'C9D3EA', italics: true })] })] : []),
      ],
      { fill: NAVY, margin: 440 },
    ),
  ];
}

function summaryBox(summary: string): Array<Paragraph | Table> {
  const paragraphs = (summary || 'No summary was generated for this session.').split(/\n+/).map((p) => p.trim()).filter(Boolean);
  return [
    box(
      paragraphs.map((p, i) => new Paragraph({ spacing: { after: i === paragraphs.length - 1 ? 0 : 160, line: 340 }, children: [run(p, { size: 23 })] })),
      { fill: CREAM, borders: { top: line(CREAM_EDGE), bottom: line(CREAM_EDGE), left: line(CREAM_EDGE), right: line(CREAM_EDGE) }, margin: 320 },
    ),
  ];
}

function insightBox(bullets: string[]): Array<Paragraph | Table> {
  const edge = line(INSIGHT_EDGE);
  return [
    new Table({
      width: { size: CONTENT_W, type: WidthType.DXA },
      columnWidths: [CONTENT_W],
      layout: TableLayoutType.FIXED,
      borders: { ...noBorders, insideHorizontal: NONE, insideVertical: NONE },
      rows: [
        new TableRow({
          cantSplit: true, // an insights box is never cut across two pages
          children: [
            new TableCell({
              width: { size: CONTENT_W, type: WidthType.DXA },
              shading: { type: ShadingType.CLEAR, color: 'auto', fill: INSIGHT_FILL },
              borders: { top: edge, bottom: edge, right: edge, left: { style: BorderStyle.SINGLE, size: 36, color: NAVY } },
              margins: { top: 160, bottom: 140, left: 280, right: 280 },
              children: [
                new Paragraph({ spacing: { after: 100 }, children: [run(' COGNIX AI ', { size: 14, color: 'FFFFFF', bold: true, spacing: 20, shade: NAVY }), run('   insights & suggestions', { size: 17, color: BLUE, italics: true })] }),
                ...bullets.map(
                  (b) =>
                    new Paragraph({
                      spacing: { after: 70, line: 280 },
                      indent: { left: 300, hanging: 220 },
                      children: [run('•  ', { size: 20, color: BLUE, bold: true }), run(b, { size: 20, color: '27304A' })],
                    }),
                ),
              ],
            }),
          ],
        }),
      ],
    }),
    spacer(260),
  ];
}

function transcript(items: TranscriptItem[], colourOf: (s: string) => string): Array<Paragraph | Table> {
  const out: Array<Paragraph | Table> = [];
  for (const item of items) {
    if (item.kind === 'turn') {
      const c = colourOf(item.speaker);
      out.push(
        new Paragraph({ keepNext: true, spacing: { before: 120, after: 80 }, children: [run(` ${item.speaker.toUpperCase()} `, { size: 17, color: c, bold: true, spacing: 20, shade: tint(c, 0.86) })] }),
        new Paragraph({ spacing: { after: 220, line: 320 }, children: [run(item.text, { size: 23, color: INK })] }),
      );
    } else {
      out.push(...insightBox(item.bullets));
    }
  }
  return out;
}

function keyInsights(insights: string[]): Array<Paragraph | Table> {
  const widths = [900, CONTENT_W - 900];
  return [
    ...sectionHeading('WHAT STOOD OUT', 'Key Insights'),
    new Table({
      width: { size: CONTENT_W, type: WidthType.DXA },
      columnWidths: widths,
      layout: TableLayoutType.FIXED,
      borders: { ...noBorders, insideHorizontal: NONE, insideVertical: NONE },
      rows: insights.map(
        (text, i) =>
          new TableRow({
            cantSplit: true,
            children: [
              new TableCell({ width: { size: widths[0], type: WidthType.DXA }, borders: { ...noBorders, bottom: line(RULE) }, margins: { top: 180, bottom: 180, left: 0, right: 100 }, children: [new Paragraph({ children: [run(String(i + 1).padStart(2, '0'), { size: 30, color: BLUE })] })] }),
              new TableCell({ width: { size: widths[1], type: WidthType.DXA }, borders: { ...noBorders, bottom: line(RULE) }, margins: { top: 180, bottom: 180, left: 100, right: 0 }, children: [new Paragraph({ spacing: { line: 300 }, children: [run(text, { size: 22, color: INK })] })] }),
            ],
          }),
      ),
    }),
  ];
}

function actionPoints(actions: string[]): Array<Paragraph | Table> {
  const widths = [760, 5400, 1900, 1578];
  const headCell = (text: string, i: number) =>
    new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      shading: { type: ShadingType.CLEAR, color: 'auto', fill: NAVY },
      borders: noBorders,
      verticalAlign: VerticalAlign.CENTER,
      margins: { top: 130, bottom: 130, left: 160, right: 120 },
      children: [new Paragraph({ children: [run(text, { size: 15, color: 'FFFFFF', bold: true, spacing: 24 })] })],
    });
  return [
    ...sectionHeading('WHAT HAPPENS NEXT', 'Action Points / Next Steps'),
    new Table({
      width: { size: CONTENT_W, type: WidthType.DXA },
      columnWidths: widths,
      layout: TableLayoutType.FIXED,
      borders: { ...noBorders, insideHorizontal: NONE, insideVertical: NONE },
      rows: [
        new TableRow({ tableHeader: true, cantSplit: true, children: ['#', 'ACTION', 'OWNER', 'DONE'].map(headCell) }),
        ...actions.map((text, i) => {
          const fill = i % 2 ? 'FFFFFF' : 'F7F8FB';
          const cell = (w: number, children: Paragraph[], extra: Record<string, unknown> = {}) =>
            new TableCell({ width: { size: w, type: WidthType.DXA }, shading: { type: ShadingType.CLEAR, color: 'auto', fill }, verticalAlign: VerticalAlign.CENTER, borders: { ...noBorders, bottom: line(RULE) }, margins: { top: 170, bottom: 170, left: 160, right: 120 }, children, ...extra });
          return new TableRow({
            cantSplit: true,
            children: [
              cell(widths[0], [new Paragraph({ children: [run(String(i + 1).padStart(2, '0'), { size: 28, color: BLUE })] })]),
              cell(widths[1], [new Paragraph({ spacing: { line: 290 }, children: [run(text, { size: 21, color: INK })] })]),
              cell(widths[2], [new Paragraph({ children: [run(' ', { size: 20 })] })]),
              cell(widths[3], [new Paragraph({ alignment: AlignmentType.CENTER, children: [run('☐', { size: 28, color: '9AA3B5' })] })]),
            ],
          });
        }),
      ],
    }),
  ];
}

export async function renderSummaryReportDocx(report: SummaryReport): Promise<Buffer> {
  const speakerIndex = new Map<string, number>();
  for (const s of report.sessions) for (const it of s.transcript) if (it.kind === 'turn' && !speakerIndex.has(it.speaker)) speakerIndex.set(it.speaker, speakerIndex.size);
  const colourOf = (speaker: string) => SPEAKER_COLOURS[(speakerIndex.get(speaker) ?? 0) % SPEAKER_COLOURS.length];

  const children: Array<Paragraph | Table> = [...cover(report), spacer(360), ...contentsTable(report)];
  for (const s of report.sessions) {
    children.push(...sessionBanner(s.number, s.date, s.title, s.description), spacer(120));
    children.push(...sectionHeading('THE SHORT VERSION', 'Summary'), ...summaryBox(s.summary), spacer(120));
    if (s.transcript.length > 0) children.push(...sectionHeading('WORD FOR WORD', 'Transcript'), ...transcript(s.transcript, colourOf));
    if (s.keyInsights.length > 0) children.push(spacer(120), ...keyInsights(s.keyInsights));
    if (s.actionPoints.length > 0) children.push(spacer(120), ...actionPoints(s.actionPoints));
  }

  const logoW = 130;
  const doc = new Document({
    creator: 'CognIX AI',
    title: report.title,
    styles: { default: { document: { run: { font: SERIF, size: 22 } } } },
    sections: [
      {
        properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1400, bottom: 1300, left: MARGIN, right: MARGIN, header: 560, footer: 560 } } },
        headers: {
          default: new Header({
            children: [
              new Paragraph({
                children: [new ImageRun({ type: 'png', data: LOGO_PNG, transformation: { width: logoW, height: Math.round(logoW * LOGO_ASPECT) }, altText: { name: 'CognIX AI logo', title: 'CognIX AI logo', description: 'CognIX AI logo' } })],
              }),
            ],
          }),
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                tabStops: [{ type: 'right' as never, position: CONTENT_W }],
                border: { top: line(RULE, 4) },
                children: [
                  run('CognIX AI  ·  Meeting Intelligence Report', { size: 16, color: MUTED }),
                  new TextRun({ text: '\tPage ', font: SERIF, size: 16, color: MUTED }),
                  new TextRun({ children: [PageNumber.CURRENT], font: SERIF, size: 16, color: MUTED }),
                  new TextRun({ text: ' of ', font: SERIF, size: 16, color: MUTED }),
                  new TextRun({ children: [PageNumber.TOTAL_PAGES], font: SERIF, size: 16, color: MUTED }),
                ],
              }),
            ],
          }),
        },
        children,
      },
    ],
  });
  return Packer.toBuffer(doc);
}
